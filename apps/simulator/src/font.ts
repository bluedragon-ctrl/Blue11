/** The 8 font bytes of character `code` (0–177), bit 7 = the leftmost pixel. */
export function glyphBytes(code: number): number[] {
  const out = [0, 0, 0, 0, 0, 0, 0, 0];
  const art = GLYPHS[String.fromCharCode(code)];
  if (code < 0o40 || code > 0o176 || !art) return out;
  art.split(' ').forEach((row, y) => {
    for (let x = 0; x < 5; x++) if (row[x] === '#') out[y] |= 0o100 >> x;
  });
  return out;
}
